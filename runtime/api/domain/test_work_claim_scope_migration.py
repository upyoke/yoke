from yoke_core.domain.migration_serving_version import declared_minimum
from yoke_core.domain.schema_common import _get_columns
from yoke_core.domain.schema_init_columns import apply_work_claim_scope_column

ENTRY_NAME = "0020_work_claim_scope"
FINAL_COLUMNS = {
    "id",
    "session_id",
    "target_kind",
    "scope",
    "claim_type",
    "claimed_at",
    "last_heartbeat",
    "released_at",
    "release_reason",
    "reason",
    "reason_intent",
    "release_reason_intent",
}


def _entry():
    directory = history_dir(migration_history_package)
    record = next(
        candidate for candidate in ordered_entries(directory)
        if candidate.name == ENTRY_NAME
    )
    return load_migration_module(directory / f"{record.name}.py", record.name)


entry = _entry()


