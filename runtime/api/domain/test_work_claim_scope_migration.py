def test_cutover_backfills_every_kind_and_drops_specialized_columns(
    specialized_db,
) -> None:
    entry.apply(specialized_db)
    entry.invariants(specialized_db)

    assert set(_get_columns(specialized_db, "work_claims")) == FINAL_COLUMNS
    rows = specialized_db.execute(
        "SELECT target_kind, scope FROM work_claims ORDER BY id"
    ).fetchall()
    assert [(row[0], row[1]) for row in rows] == [
        ("item", '{"item_id":10}'),
        ("process", '{"conflict_group":"doctor:yoke","process_key":"DOCTOR"}'),
        ("steering", '{"project_id":7}'),
    ]


def test_cutover_enforces_active_scope_and_process_conflict_uniqueness(
    specialized_db,
) -> None:
    entry.apply(specialized_db)
    specialized_db.commit()
    with pytest.raises(psycopg.errors.UniqueViolation):
        specialized_db.execute(
            "INSERT INTO work_claims "
            "(session_id, target_kind, scope, claimed_at, last_heartbeat) "
            "VALUES ('other', 'item', '{\"item_id\":10}', 't4', 't4')"
        )
    specialized_db.rollback()

    with pytest.raises(psycopg.errors.UniqueViolation):
        specialized_db.execute(
            "INSERT INTO work_claims "
            "(session_id, target_kind, scope, claimed_at, last_heartbeat) "
            "VALUES ('other', 'process', "
            "'{\"conflict_group\":\"doctor:yoke\",\"process_key\":\"DOCTOR-ALT\"}', "
            "'t4', 't4')"
        )
    specialized_db.rollback()


def test_cutover_is_idempotent_and_declares_serving_floor(specialized_db) -> None:
    entry.apply(specialized_db)
    entry.apply(specialized_db)
    entry.invariants(specialized_db)
    assert declared_minimum(entry) == entry.MINIMUM_SERVING_VERSION
