"""Shared HTML page shell, escaping, wrapping and line measurement.

Views are static, dependency-free HTML. Every emitted line stays within 80
columns so the generated pages remain readable and stay inside the
shared 350-line teaching limit without minifying.
"""

from __future__ import annotations

import html
import re
from posixpath import dirname, normpath, relpath

WIDTH = 80
LINE_LIMIT = 350
NAV = (
    ("index.html", "Overview"),
    ("concepts.html", "Concepts"),
    ("surfaces.html", "Surfaces"),
    ("scenarios.html", "Scenarios"),
    ("evidence.html", "Evidence"),
    ("boundaries.html", "Boundaries"),
    ("gaps.html", "Gaps"),
)
_BASE = "/teaching/views/"


def esc(text) -> str:
    return html.escape(str(text), quote=True)


def wrapped_lines(text: str) -> int:
    """Count lines as displayed at the 80-column reference width."""
    return sum(max(1, -(-len(line) // WIDTH)) for line in text.splitlines())


def wrap(text: str, indent: str = "") -> list[str]:
    """Wrap markup at spaces outside tags, so a tag never splits across lines.

    A token longer than the width (a long link) keeps a line to itself.
    """
    tokens = re.findall(r"(?:<[^>]*>|[^\s<])+", text)
    lines: list[str] = []
    current = indent
    for token in tokens:
        candidate = f"{current} {token}" if current.strip() else indent + token
        if len(candidate) > WIDTH and current.strip():
            lines.append(current)
            current = indent + token
        else:
            current = candidate
    return lines + [current] if current.strip() or not lines else lines


def href(from_page: str, to_page: str, anchor: str | None = None) -> str:
    """Relative link between two page paths, both relative to ``views/``.

    Live pages sit beside the views as ``../live/...``; resolving both paths
    under one fixed base keeps ``..`` segments independent of the cwd.
    """
    start = dirname(normpath(_BASE + from_page))
    target = relpath(normpath(_BASE + to_page), start=start)
    return esc(f"{target}#{anchor}" if anchor else target)


def link(from_page: str, to_page: str, label: str, anchor: str | None = None) -> str:
    return f'<a href="{href(from_page, to_page, anchor)}">{esc(label)}</a>'


def badge(status: str) -> str:
    return f'<i class="s {esc(status)}">{esc(status)}</i>'


def page(path: str, title: str, body: list[str]) -> str:
    """Wrap body lines in the shared shell for the view at ``path``."""
    nav = " · ".join(link(path, target, label) for target, label in NAV)
    head = [
        "<!doctype html>",
        '<html lang="en">',
        "<head>",
        '<meta charset="utf-8">',
        '<meta name="viewport" content="width=device-width, initial-scale=1">',
        f"<title>{esc(title)} · Yoke teaching prototype</title>",
        f'<link rel="stylesheet" href="{href(path, "style.css")}">',
        "</head>",
        "<body>",
        "<nav>",
        *wrap(nav),
        "</nav>",
        "<main>",
        f"<h1>{esc(title)}</h1>",
    ]
    tail = [
        "</main>",
        "<footer>Generated by docs/teaching/tools/build.py from",
        "docs/teaching/model. Edit the model, then rebuild.</footer>",
        "</body>",
        "</html>",
    ]
    return "\n".join(head + body + tail) + "\n"


def field_line(label: str, value: str, indent: str = "") -> list[str]:
    """One labelled, wrapped detail line; empty values render nothing."""
    if not value:
        return []
    return wrap(f"<div><b>{esc(label)}:</b> {value}</div>", indent)


def text_field(label: str, value, indent: str = "") -> list[str]:
    if isinstance(value, list):
        value = " · ".join(str(v) for v in value)
    return field_line(label, esc(value) if value else "", indent)


def links_field(
    label: str, from_page: str, targets: list[tuple[str, str, str]], indent: str = ""
) -> list[str]:
    """``targets`` holds ``(page, anchor, label)`` triples."""
    value = ", ".join(link(from_page, p, text, a) for p, a, text in targets)
    return field_line(label, value, indent)


def code_field(label: str, values: list[str], indent: str = "") -> list[str]:
    value = ", ".join(f"<code>{esc(v)}</code>" for v in values)
    return field_line(label, value, indent)
