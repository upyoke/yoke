"""Assemble the public installer's single downloadable Python program."""

from __future__ import annotations

import argparse
import ast
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
PARTS = (
    "options",
    "diagnostics",
    "distribution",
    "verification",
    "resolution",
    "installation",
)

PATH_DOCTOR = ROOT.parents[1] / "packages/yoke-cli/src/yoke_cli/config/path_doctor.py"


def _path_doctor_constant(name: str) -> str:
    """Return a string constant from path_doctor, the owner of uv's messages."""
    for node in ast.parse(PATH_DOCTOR.read_text()).body:
        if (
            isinstance(node, ast.Assign)
            and [getattr(target, "id", None) for target in node.targets] == [name]
            and isinstance(node.value, ast.Constant)
        ):
            return node.value.value
    raise SystemExit(f"installer_constant_missing: {name} not found in {PATH_DOCTOR}")


def render() -> str:
    parts = [(ROOT / "source" / f"{name}.py.inc").read_text() for name in PARTS]
    source = (
        "# Generated by packaging/public-installer/build.py; edit source/*.py.inc.\n"
        + parts[0]
        + "\nCLI_RUNTIME_SOURCE = "
        + repr(
            (
                ROOT.parents[1]
                / "packages/yoke-cli/src/yoke_cli/config/cli_release_runtime.py"
            ).read_text()
        )
        + "\nUV_ALREADY_CONFIGURED = "
        + repr(_path_doctor_constant("_UV_ALREADY_CONFIGURED"))
        + "\n"
        + "\n".join(parts[1:])
        + '\nif __name__ == "__main__":\n    raise SystemExit(main())\n'
    )

    return subprocess.run(
        [
            sys.executable,
            "-m",
            "ruff",
            "format",
            "--stdin-filename",
            str(ROOT / "install.py"),
            "-",
        ],
        input=source,
        capture_output=True,
        text=True,
        check=True,
    ).stdout


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    options = parser.parse_args()
    expected = render()
    target = ROOT / "install.py"
    if options.check:
        if target.read_text() != expected:
            parser.exit(
                1,
                "installer_source_drift: run yoke dev run -- python3 packaging/public-installer/build.py and commit the output\n",
            )
    else:
        target.write_text(expected)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
