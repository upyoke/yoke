"""Durable per-run release phase timings, written from the driver's own records.

Every timing scope that names a run (driver preflight, the watched child, the
pipeline, the pinned re-exec) sends its start/end records here when it closes.
The rows are diagnostics for `yoke deployment-runs timings`; nothing
operational reads them, and a refused write never fails the deployment.
"""

from __future__ import annotations

import json
from collections.abc import Mapping, Sequence
from typing import Any

from yoke_contracts.timestamps import InvalidInstant, parse_instant

from yoke_core.domain import db_backend
from yoke_core.domain.db_helpers import instant_parameter

DEPLOYMENT_RUN_TIMINGS_SQL = """
CREATE TABLE IF NOT EXISTS deployment_run_timings (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id TEXT NOT NULL REFERENCES deployment_runs(id),
    batch_id TEXT NOT NULL CHECK(TRIM(batch_id) <> ''),
    sequence INTEGER NOT NULL CHECK(sequence >= 0),
    step TEXT NOT NULL CHECK(TRIM(step) <> ''),
    phase TEXT NOT NULL CHECK(phase IN ('start','end')),
    recorded_at TIMESTAMPTZ NOT NULL,
    elapsed_ms DOUBLE PRECISION,
    outcome TEXT,
    record TEXT NOT NULL,
    UNIQUE(batch_id, sequence)
);
""".strip()

#: Heartbeat ``running`` pulses report liveness while a step runs; a finished
#: run's timing is fully described by its start and end records.
PERSISTED_PHASES = frozenset({"start", "end"})
MAX_BATCH_RECORDS = 2000


class TimingRecordInvalid(ValueError):
    """One submitted record cannot be stored as a timing row."""


def _p(conn: Any) -> str:
    return "%s" if db_backend.connection_is_postgres(conn) else "?"


def persistable(records: Sequence[Mapping[str, Any]]) -> list[dict[str, Any]]:
    """Return the records a timing scope sends for durable storage."""
    return [dict(r) for r in records if r.get("phase") in PERSISTED_PHASES]


def _validated(run_id: str, index: int, record: Any) -> tuple[Any, ...]:
    where = f"records[{index}]"
    if not isinstance(record, Mapping):
        raise TimingRecordInvalid(f"{where} must be an object")
    if record.get("run_id") != run_id:
        raise TimingRecordInvalid(
            f"{where}.run_id must equal the target run {run_id!r}"
        )
    step = record.get("step")
    if not isinstance(step, str) or not step.strip():
        raise TimingRecordInvalid(f"{where}.step must be a non-empty string")
    phase = record.get("phase")
    if phase not in PERSISTED_PHASES:
        raise TimingRecordInvalid(f"{where}.phase must be 'start' or 'end'")
    try:
        recorded_at = parse_instant(record.get("timestamp"))
    except (InvalidInstant, TypeError) as exc:
        raise TimingRecordInvalid(f"{where}.timestamp must be a UTC instant") from exc
    elapsed = record.get("elapsed_ms")
    if elapsed is not None and (
        isinstance(elapsed, bool) or not isinstance(elapsed, (int, float))
    ):
        raise TimingRecordInvalid(f"{where}.elapsed_ms must be a number")
    outcome = record.get("outcome")
    if outcome is not None and not isinstance(outcome, str):
        raise TimingRecordInvalid(f"{where}.outcome must be a string")
    return (
        step,
        phase,
        recorded_at,
        elapsed,
        outcome,
        json.dumps(record, sort_keys=True),
    )


def record_timings(
    conn: Any, *, run_id: str, batch_id: str, records: Sequence[Any]
) -> dict[str, int]:
    """Store one scope's batch; a replayed batch inserts nothing new."""
    if not batch_id.strip():
        raise TimingRecordInvalid("batch_id must be non-empty")
    if len(records) > MAX_BATCH_RECORDS:
        raise TimingRecordInvalid(
            f"records holds {len(records)} entries; the limit is {MAX_BATCH_RECORDS}"
        )
    rows = [_validated(run_id, index, record) for index, record in enumerate(records)]
    p = _p(conn)
    if (
        conn.execute(
            f"SELECT 1 FROM deployment_runs WHERE id={p}", (run_id,)
        ).fetchone()
        is None
    ):
        raise LookupError(f"deployment run {run_id!r} not found")
    recorded = 0
    for sequence, (step, phase, at, elapsed, outcome, raw) in enumerate(rows):
        cursor = conn.execute(
            "INSERT INTO deployment_run_timings "
            "(run_id,batch_id,sequence,step,phase,recorded_at,elapsed_ms,outcome,record) "
            f"VALUES ({p},{p},{p},{p},{p},{p},{p},{p},{p}) "
            "ON CONFLICT (batch_id, sequence) DO NOTHING",
            (
                run_id,
                batch_id,
                sequence,
                step,
                phase,
                instant_parameter(conn, at),
                elapsed,
                outcome,
                raw,
            ),
        )
        recorded += max(cursor.rowcount, 0)
    return {"recorded": recorded, "already_recorded": len(rows) - recorded}


def run_timings(conn: Any, run_id: str) -> list[dict[str, Any]]:
    """Return a run's stored records in recorded order, as the driver wrote them."""
    cursor = conn.execute(
        "SELECT record FROM deployment_run_timings "
        f"WHERE run_id={_p(conn)} ORDER BY recorded_at, batch_id, sequence",
        (run_id,),
    )
    return [json.loads(str(row[0])) for row in cursor.fetchall()]


def step_summary(records: Sequence[Mapping[str, Any]]) -> list[dict[str, Any]]:
    """Total each step's ended elapsed time, in first-seen order."""
    steps: dict[str, dict[str, Any]] = {}
    for record in records:
        if record.get("phase") != "end":
            continue
        step = steps.setdefault(
            str(record["step"]),
            {"step": record["step"], "elapsed_ms": 0.0, "count": 0, "outcomes": []},
        )
        step["elapsed_ms"] = round(
            step["elapsed_ms"] + float(record.get("elapsed_ms") or 0), 3
        )
        step["count"] += 1
        if record.get("outcome") not in step["outcomes"]:
            step["outcomes"].append(record.get("outcome"))
    return list(steps.values())


